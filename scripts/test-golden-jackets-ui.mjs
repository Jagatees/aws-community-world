import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';

const baseUrl = process.env.COMMUNITY_TEST_URL || 'http://127.0.0.1:5174';
const records = JSON.parse(await readFile(new URL('../src/data/golden-jackets.json', import.meta.url), 'utf8'));
const mappedCount = records.filter((r) => r.country).length;
const browser = await chromium.launch({ headless: true });
await mkdir('tmp/golden-jackets-qa', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(`${baseUrl}/?tab=aws-ambassadors&view=list`);
  await page.getByRole('tab', { name: 'Golden Jackets', exact: true }).click();
  await page.getByRole('heading', { name: 'Golden Jackets', exact: true }).waitFor();
  await page.getByText(`${records.length} entries`, { exact: true }).waitFor();
  assert.equal(new URL(page.url()).searchParams.get('tab'), 'golden-jackets');
  assert.equal(await page.locator('article').count(), Math.min(60, records.length));
  await page.getByRole('searchbox').fill('Ricardo Gulias');
  await page.getByRole('button', { name: 'Ricardo Gulias', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await page.getByText('Approximate city location.', { exact: true }).waitFor();
  const source = page.getByRole('dialog').getByRole('link', { name: 'Golden Jackets Brazil (independent community)', exact: true });
  assert.equal(await source.getAttribute('href'), 'https://goldenjacketsbrazil.com/#members');
  await page.waitForFunction(() => {
    const portrait = document.querySelector('[role="dialog"] img');
    return portrait?.complete && portrait.naturalWidth > 0;
  });
  await page.screenshot({ path: 'tmp/golden-jackets-qa/profile.png' });
  await page.keyboard.press('Escape');
  await page.getByRole('searchbox').fill('Donghee Kim');
  await page.getByRole('button', { name: 'Donghee Kim', exact: true }).click();
  await page.getByText('Country not confirmed. Not placed on the globe.', { exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('searchbox').fill('');
  await page.getByRole('button', { name: 'Alumni', exact: true }).click();
  await page.getByText(`${records.filter((r) => r.recognitionStatus === 'alumni').length} entries`, { exact: true }).waitFor();
  await page.getByRole('button', { name: 'All', exact: true }).click();
  await page.getByRole('button', { name: 'All Countries', exact: true }).click();
  await page.getByRole('searchbox').last().fill('Brazil');
  await page.getByRole('option', { name: /Brazil/ }).click();
  await page.keyboard.press('Escape');
  await page.reload();
  await page.getByText(`${records.filter((r) => r.country === 'Brazil').length} entries`, { exact: true }).waitFor();
  await page.screenshot({ path: 'tmp/golden-jackets-qa/directory.png' });
  await page.goto(`${baseUrl}/?tab=golden-jackets&view=icons`);
  await page.getByText('Golden Jacket archive', { exact: true }).waitFor();
  await page.screenshot({ path: 'tmp/golden-jackets-qa/gallery.png' });
  await page.goto(`${baseUrl}/?tab=golden-jackets&view=orbit`);
  await page.getByText(`Golden Jackets · ${mappedCount} mapped / ${records.length} profiles`, { exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelectorAll('[data-globe-marker]').length > 0);
  await page.waitForTimeout(1500);
  await page.screenshot({ path: 'tmp/golden-jackets-qa/earth.png' });
  assert.deepEqual(errors, []);
  console.log('Golden Jackets: desktop tab, sources, unmapped profiles, alumni filter, country filter, URL reload, Gallery and Earth passed.');
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  mobile.on('pageerror', (error) => errors.push(error.message));
  await mobile.goto(`${baseUrl}/?tab=heroes&view=list`);
  await mobile.getByRole('button', { name: 'Categories', exact: true }).click();
  await mobile.getByRole('button', { name: 'Golden Jackets', exact: true }).click();
  await mobile.getByRole('heading', { name: 'Golden Jackets', exact: true }).waitFor();
  await mobile.getByText(`${records.length} entries`, { exact: true }).waitFor();
  assert.equal(await mobile.locator('.mobile-active-category strong').innerText(), String(records.length));
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await mobile.waitForFunction(() => {
    const portrait = document.querySelector('article img');
    return portrait?.complete && portrait.naturalWidth > 0;
  });
  await mobile.screenshot({ path: 'tmp/golden-jackets-qa/mobile-directory.png' });
  await mobile.goto(`${baseUrl}/?tab=golden-jackets&view=flat`);
  await mobile.getByRole('button', { name: 'Zoom in flat map', exact: true }).waitFor();
  assert.ok(await mobile.locator('[data-marker-interactive="true"]').count() > 0);
  await mobile.screenshot({ path: 'tmp/golden-jackets-qa/mobile-map.png' });
  assert.deepEqual(errors, []);
  console.log('Golden Jackets: mobile navigation, Directory and Map passed without runtime errors or overflow.');
} finally { await browser.close(); }
